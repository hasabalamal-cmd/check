export const getLanguage = (): Language =>
  localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ar';

export const saveLanguage = (language: Language): void => {
  localStorage.setItem(STORAGE_KEY, language);
};

export const translate = (text: string, language: Language = getLanguage()): string => {
  if (language === 'ar') return text;

  const translationsForCount: Array<[RegExp, (count: string) => string]> = [
    [/^متبقي (\d+) أيام$/, (count) => `${count} days remaining`],
    [/^متبقي (\d+) يوم$/, (count) => `${count} day${count === '1' ? '' : 's'} remaining`],
    [/^متأخر منذ (\d+) يوم$/, (count) => `${count} day${count === '1' ? '' : 's'} overdue`],
    [/^متأخر \((\d+) يوم\)$/, (count) => `Overdue (${count} day${count === '1' ? '' : 's'})`],
    [/^(\d+) فواتير$/, (count) => `${count} invoice${count === '1' ? '' : 's'}`],
    [/^(\d+) شيكات$/, (count) => `${count} check${count === '1' ? '' : 's'}`],
    [/^(\d+) شيك$/, (count) => `${count} check${count === '1' ? '' : 's'}`],
    [/^(\d+) فاتورة$/, (count) => `${count} invoice${count === '1' ? '' : 's'}`],
    [/^(\d+) محل$/, (count) => `${count} shop${count === '1' ? '' : 's'}`],
    [/^(\d+) شيك قادم$/, (count) => `${count} upcoming check${count === '1' ? '' : 's'}`],
    [/^(\d+) شيك متأخر$/, (count) => `${count} overdue check${count === '1' ? '' : 's'}`],
    [/^(\d+) شيك تم صرفه$/, (count) => `${count} cashed check${count === '1' ? '' : 's'}`],
  ];

  for (const [pattern, render] of translationsForCount) {
    const match = text.match(pattern);
    if (match) return render(match[1]);
  }

  return translations[text] || text;
};
